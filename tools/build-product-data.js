const fs = require('fs');
const path = require('path');
const Database = require('better-sqlite3');

const root = path.join(__dirname, '..');
const db = new Database(path.join(root, 'data', 'flowpicker.db'), { readonly: true });

const layerRows = db.prepare(`
  SELECT id, name, optional, position
  FROM layers
  ORDER BY position
`).all();

const chipRows = db.prepare(`
  SELECT layer_id, key
  FROM layer_chip_keys
  ORDER BY layer_id, position
`).all();

const optionRows = db.prepare(`
  SELECT layer_id, id, name, position
  FROM options
  ORDER BY layer_id, position
`).all();

const attrRows = db.prepare(`
  SELECT layer_id, option_id, key, value
  FROM option_attrs
`).all();

const chipsByLayer = new Map();
for (const row of chipRows) {
  if (!chipsByLayer.has(row.layer_id)) chipsByLayer.set(row.layer_id, []);
  chipsByLayer.get(row.layer_id).push(row.key);
}

const attrsByOption = new Map();
for (const row of attrRows) {
  const key = `${row.layer_id}\u0001${row.option_id}`;
  if (!attrsByOption.has(key)) attrsByOption.set(key, {});
  attrsByOption.get(key)[row.key] = row.value;
}

const optionsByLayer = new Map();
for (const row of optionRows) {
  if (!optionsByLayer.has(row.layer_id)) optionsByLayer.set(row.layer_id, []);
  const attrs = attrsByOption.get(`${row.layer_id}\u0001${row.id}`) || {};
  optionsByLayer.get(row.layer_id).push({ id: row.id, name: row.name, ...attrs });
}

const layers = layerRows.map(row => ({
  id: row.id,
  name: row.name,
  optional: row.optional === 1,
  chipKeys: chipsByLayer.get(row.id) || [],
  options: optionsByLayer.get(row.id) || [],
}));

function jsLiteral(value) {
  return JSON.stringify(value, null, 2).replace(/[<>\u007f-\uffff]/g, char =>
    `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`
  );
}

const out = `// Generated by tools/build-product-data.js from data/flowpicker.db.\n` +
  `window.FLOWPICKER_LAYERS = ${jsLiteral(layers)};\n`;

fs.writeFileSync(path.join(root, 'data', 'product-data.js'), out, 'utf8');
console.log(`Wrote data/product-data.js (${layers.reduce((sum, layer) => sum + layer.options.length, 0)} products)`);
